public class RectangleStarPattern {
    public static void main(String[] args) {
        int R = 3;
        int C = 5;
        for ( int row = 1; row <= R; row++) {
            for ( int col = 1; col <= C; col++) {
                System.out.print("*");
            }
            System.out.println();
        }
    
    }
    
    }
